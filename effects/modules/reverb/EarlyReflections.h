/**
    Early reflections: the discrete echoes of a room's walls, ahead of its tail.

    Four profiles (ErProfile Room, Chamber, Hall, Cathedral - Off has none),
    each a tap pattern from an image-source model of a shoebox room. The tables
    below are the output of tools/reverb/gen_er_profiles.py, which says how
    they were chosen; regenerate rather than hand-edit them. A tap is a delay
    after the predelayed direct sound and a gain. First-order taps play as
    they are; higher-order ones go through a one-pole low pass, the profile's
    "dark" frequency, because every extra bounce loses top.

    Per effects channel, every tap time is jittered by up to 4 % and every
    higher-order sign drawn, both from the channel's noise key, so thirty-two
    returns of the same room spread instead of summing into one comb.

    Size scales every time - the taps and the tail delay - the way it scales
    the reverb model's lines.

    The tail delay is where the model takes over. With reflections on, the
    model's input is the same predelayed signal that much later, so switching
    them on moves the tail back to make room for them; with them off it is not
    delayed at all.

    buildErTapSet() runs on the audio thread when a transition starts: two
    dozen hashes and multiplies, no allocation.
*/

struct ErTapSpec
{
    float ms;               // after the direct sound, at Size 1
    float gain;             // a profile's taps carry a quarter of the dry's energy
    std::uint8_t order;     // bounces: 1 plays as is, 2 and more through the dark filter
};

