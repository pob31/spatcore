struct ErProfileSpec
{
    const ErTapSpec* taps;
    int numTaps;
    float tailDelayMs;      // where the model's tail takes over, at Size 1
    float darkHz;           // the higher-order taps' low pass
};

/** Indexed by ErProfile. */
inline constexpr ErProfileSpec kErProfiles[] =
{
    { nullptr,       0,  0.0f, 20000.0f },          // Off
    { kErRoom,      16,  7.0f,  6000.0f },
    { kErChamber,   18, 11.0f,  8000.0f },
    { kErHall,      20, 29.0f,  5000.0f },
    { kErCathedral, 24, 68.0f,  4000.0f },
};

static_assert (sizeof (kErProfiles) / sizeof (kErProfiles[0]) == static_cast<size_t> (ErProfile::Count),
               "one spec per ErProfile id");

/** How far each tap time may move per channel, either way. */
inline constexpr float kErJitter = 0.04f;

/** The profile a stored id runs: anything this build does not know is Off. */
inline int resolveErProfile (int stored) noexcept
{
    return (stored > 0 && stored < static_cast<int> (ErProfile::Count)) ? stored : 0;
}

/** 1 - exp(-2 pi f / sr) without libm - the reverb's tone filter's law, so a
    render of the same session hashes the same on every platform. */
inline float erOnePoleCoef (float hz, double sampleRate) noexcept
{
    const float sr = static_cast<float> (sampleRate > 0.0 ? sampleRate : 48000.0);
    const float f = hz < sr * 0.49f ? hz : sr * 0.49f;
    const float x = 6.2831853071795864f * f / sr;
    return 1.0f - spatcore::dsp::FastDecibels::exp2 (-x * 1.4426950408889634f);
}

/** One profile built for one channel at one size, in samples. */
struct ErTapSet
{
    static constexpr int kMaxTaps = 24;

    int profile = 0;                // resolved: 0 = Off, no taps and no tail delay
    float size = 1.0f;              // the quantised size it was built at
    int numFirst = 0;               // taps [0, numFirst) are first order
    int numTaps = 0;
    int delay[kMaxTaps] = {};       // samples after the direct sound
    float gain[kMaxTaps] = {};      // signed
    int tailDelay = 0;              // samples
    int maxRead = 0;                // the longest delay of all of them
    float darkCoef = 1.0f;

    bool isOn() const noexcept      { return profile != 0; }

    /** Whether this is the set (profile, size) builds. Off is Off at any size. */
    bool matches (int resolvedProfile, float quantisedSize) const noexcept
    {
        if (profile == 0 || resolvedProfile == 0)
            return profile == resolvedProfile;

        return profile == resolvedProfile && size == quantisedSize;
    }
};

/** Builds `profile` at `size` for the channel with `noiseKey`. Realtime-safe. */
inline void buildErTapSet (ErTapSet& set, int profile, float size, double sampleRate,
                           std::uint32_t noiseKey) noexcept
{
    const int p = resolveErProfile (profile);
    const ErProfileSpec& spec = kErProfiles[p];
    const double samplesPerMs = (sampleRate > 0.0 ? sampleRate : 48000.0) * 0.001;

    set.profile = p;
    set.size = size;
    set.numFirst = 0;
    set.numTaps = 0;
    set.tailDelay = static_cast<int> (static_cast<double> (spec.tailDelayMs) * size * samplesPerMs + 0.5);
    set.maxRead = set.tailDelay;
    set.darkCoef = erOnePoleCoef (spec.darkHz, sampleRate);

    // A stream of its own, apart from the one that picks the FDN's network.
    const std::uint32_t key = spatcore::dsp::FrDiffusion::makeKey (static_cast<int> (noiseKey & 0x7FFFFFFFu),
                                                                    static_cast<int> (ModuleId::Reverb) + 64);

    // First order first, then the rest; each group keeps its arrival order.
    for (int pass = 0; pass < 2; ++pass)
    {
        for (int j = 0; j < spec.numTaps && set.numTaps < ErTapSet::kMaxTaps; ++j)
        {
            const ErTapSpec& t = spec.taps[j];
            const bool first = t.order == 1;
            if (first != (pass == 0))
                continue;

            const float jitter = 1.0f + kErJitter * spatcore::dsp::FrDiffusion::hashNoiseBipolar (2u * static_cast<std::uint32_t> (j), key);
            int d = static_cast<int> (static_cast<double> (t.ms * jitter) * size * samplesPerMs + 0.5);
            if (d < 1)
                d = 1;

            float g = t.gain;
            if (! first && spatcore::dsp::FrDiffusion::hashNoiseBipolar (2u * static_cast<std::uint32_t> (j) + 1u, key) < 0.0f)
                g = -g;

            set.delay[set.numTaps] = d;
            set.gain[set.numTaps] = g;
            ++set.numTaps;
            if (first)
                ++set.numFirst;
            if (d > set.maxRead)
                set.maxRead = d;
        }
    }
}

/** The longest read any profile can make at the largest size, in samples. */
inline int erMaxReadSamples (double sampleRate) noexcept
{
    const double samplesPerMs = (sampleRate > 0.0 ? sampleRate : 48000.0) * 0.001;
    double longest = 0.0;

    for (const ErProfileSpec& spec : kErProfiles)
    {
        if (spec.tailDelayMs > longest)
            longest = spec.tailDelayMs;

        for (int j = 0; j < spec.numTaps; ++j)
        {
            const double ms = static_cast<double> (spec.taps[j].ms) * (1.0 + kErJitter);
            if (ms > longest)
                longest = ms;
        }
    }

    return static_cast<int> (longest * kReverbMaxSize * samplesPerMs) + 2;
}

